/** Plaatspagina's sturen op de kale plaatsnaam ("comares", niet "comares spanje"): daar zit het meeste volume en daar rankt de site al op. */
export function placeKeyword(lang: KwLang, placeSlug: string, sub = ''): string | undefined {
  const t = placeTemplates[lang]?.[sub];
  return t?.replace('{p}', placeSlug.replace(/-/g, ' '));
}

