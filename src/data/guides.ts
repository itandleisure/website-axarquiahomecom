export const guideHref = (lang: Lang, g: GuideMeta) => g.path ?? `${guideBase[lang]}${g.slug}/`;
/** Gidsen die in het gidsenoverzicht staan (zonder regiopagina's) */
export const guideList = (lang: Lang) => guidesBy[lang].filter((g) => !g.path);
